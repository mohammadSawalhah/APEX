  USING INDEX  ENABLE, 
	 CONSTRAINT "EMPLOYEES_PHONE_9DEGITS" CHECK (LENGTH(PHONE) = 9) DISABLE, 
	 CONSTRAINT "EMPLOYEES_USER_FK" FOREIGN KEY ("USER_ID")
	  REFERENCES "MOBASHER"."APP_USERS" ("ID") ENABLE, 
	 CONSTRAINT "EMPLOYEES_SELLER_FK" FOREIGN KEY ("SELLER_ID")
	  REFERENCES "MOBASHER"."SELLERS" ("ID") ENABLE
   )  DEFAULT COLLATION "USING_NLS_COMP" ;