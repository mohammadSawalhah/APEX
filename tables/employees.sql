	"JOB_NO" VARCHAR2(255) COLLATE "USING_NLS_COMP", 
	"PHONE" VARCHAR2(255) COLLATE "USING_NLS_COMP", 
	"COUNTRY_CALL_KEY" VARCHAR2(25) COLLATE "USING_NLS_COMP", 
	"EMAIL" VARCHAR2(255) COLLATE "USING_NLS_COMP", 
	"AVATAR_URL" VARCHAR2(1000) COLLATE "USING_NLS_COMP", 
