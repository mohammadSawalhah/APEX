	 CONSTRAINT "EMPLOYEES_NID_10DEGITS" CHECK (LENGTH(IDENTITY_NUMBER) = 10) DISABLE, 
	 CONSTRAINT "EMPLOYEES_NID_UNQ" UNIQUE ("IDENTITY_NUMBER")
  USING INDEX  ENABLE, 
	 CONSTRAINT "EMPLOYEES_PHONE_UNQ" UNIQUE ("PHONE") DISABLE, 
	 CONSTRAINT "EMPLOYEES_NID_CHECK" CHECK ( "IDENTITY_NUMBER" IS NOT NULL ) ENABLE, 
